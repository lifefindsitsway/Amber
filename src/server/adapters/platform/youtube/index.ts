/** IE_NAMEs of the pinned yt-dlp for the URLs `parse` accepts; matched whole, so each is listed. */
export const YOUTUBE_EXTRACTORS = ["youtube", "youtube:tab", "youtube:playlist"] as const;
/** yt-dlp marks the original-language automatic track with this suffix. */
const ORIGINAL_SUFFIX = "-orig";
/** Cookies yt-dlp needs to consider a YouTube session logged in. */
const LOGIN_COOKIE = "LOGIN_INFO";
const SAPISID_COOKIES = ["SAPISID", "__Secure-1PAPISID", "__Secure-3PAPISID"];
/** The page whose ytcfg tells whether the cookies are a working login. */
const HOME_HOST = "www.youtube.com";
const HOME_URL = `https://${HOME_HOST}/`;
/** The page's `ytcfg.set({...});` calls, matched like yt-dlp's `extract_ytcfg`. */
const YTCFG_PATTERN = /ytcfg\.set\s*\(\s*(\{.+?\})\s*\)\s*;/g;

/** The first boolean `LOGGED_IN` of the page's ytcfg objects; `undefined` when none has one. */
export function ytcfgLoggedIn(html: string): boolean | undefined {
  for (const match of html.matchAll(YTCFG_PATTERN)) {
    try {
      const value = (JSON.parse(match[1] as string) as { LOGGED_IN?: unknown }).LOGGED_IN;
      if (typeof value === "boolean") {
        return value;
      }
    } catch {
      // Not JSON (a call with a key/value pair, or a cut-off match): look at the next one.
    }
  }
  return undefined;
}

export interface YoutubeAdapterOptions {
  ytDlp: YtDlp;
  /** Login checks read the youtube.com page with the stored cookies. */
  http?: OutboundHttpClient;
  newId?: () => string;
  now?: () => number;
}

interface CaptionTrack {
  ext?: string;
  name?: string;
}

interface VideoInfo {
  title?: string;
  duration?: number;
  thumbnail?: string;
  timestamp?: number;
  release_timestamp?: number;
  channel?: string;
  channel_id?: string;
  language?: string;
  chapters?: YtDlpChapter[] | null;
  subtitles?: Record<string, CaptionTrack[]>;
  automatic_captions?: Record<string, CaptionTrack[]>;
}

interface FlatPlaylist {
  title?: string;
  entries?: Array<{ id?: string; title?: string; duration?: number }>;
}

interface TrackLocator {
  key: string;
  automatic: boolean;
}

function isAuthProblem(error: unknown): boolean {
  return error instanceof AmberError && (error.appError.class === "auth_required" || error.appError.class === "platform_blocked");
}

/**
 * The tracks of a video in yt-dlp's terms (pinned release, `youtube/_video.py`):
 * `subtitles` are uploader tracks; in `automatic_captions` the key ending in `-orig` is
 * the original-language automatic track and every other key is a platform translation.
 */
export function captionTracks(info: Pick<VideoInfo, "subtitles" | "automatic_captions">): SubtitleTrackRef[] {
  const tracks: SubtitleTrackRef[] = [];
  const locator = (value: TrackLocator) => JSON.stringify(value);
  for (const [key, formats] of Object.entries(info.subtitles ?? {})) {
    if (key === "live_chat") {
      continue;
    }
    const label = formats[0]?.name;
    tracks.push({ locator: locator({ key, automatic: false }), language: languageTag(key), ...(label === undefined ? {} : { label }), autoGenerated: false, translated: false });
  }
  const automatic = Object.entries(info.automatic_captions ?? {});
  const originals = new Set(automatic.filter(([key]) => key.endsWith(ORIGINAL_SUFFIX)).map(([key]) => key.slice(0, -ORIGINAL_SUFFIX.length)));
  for (const [key, formats] of automatic) {
    const original = key.endsWith(ORIGINAL_SUFFIX);
    if (!original && originals.has(key)) {
      // The same original track is also listed without the suffix for compatibility.
      continue;
    }
    const label = formats[0]?.name;
    tracks.push({
      locator: locator({ key, automatic: true }),
      language: languageTag(original ? key.slice(0, -ORIGINAL_SUFFIX.length) : key),
      ...(label === undefined ? {} : { label }),
      autoGenerated: true,
      translated: !original,
    });
  }
  return tracks;
}

function escapeRegex(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * `PlatformSourceAdapter` for YouTube. Everything goes through
 * yt-dlp (which needs Deno for the JS challenge). Public videos are fetched as a guest
 * first; only when YouTube demands a login and the user has one is the call repeated
 * once with cookies.
 */
export class YoutubeAdapter implements PlatformSourceAdapter {
  readonly kind = "youtube" as const;
  readonly cookieDomains = ["youtube.com"] as const;
  private readonly options: YoutubeAdapterOptions;
  private readonly newId: () => string;
  private readonly now: () => number;

  constructor(options: YoutubeAdapterOptions) {
    this.options = options;
    this.newId = options.newId ?? monotonicFactory();
    this.now = options.now ?? Date.now;
  }

  parse(url: string): ParsedPlatformUrl | null {
    return parseYoutubeUrl(url);
  }

  async fetchMetadata(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformMetadata> {
    const { value: info } = await this.guestFirst(auth, (cookies) =>
      this.options.ytDlp.json<VideoInfo>({
        args: ["--dump-single-json", "--skip-download", "--no-playlist", "--write-subs", "--write-auto-subs", watchUrl(ref.platformContentId)],
        extractors: YOUTUBE_EXTRACTORS,
        ...(cookies === undefined ? {} : { cookies }),
        signal,
        timeoutMs: PLATFORM_METADATA_TIMEOUT_MS,
      }),
    );
    const published = info.timestamp ?? info.release_timestamp;
    return {
      title: info.title ?? ref.platformContentId,
      durationMs: secondsToMs(info.duration ?? 0),
      ...(info.thumbnail === undefined ? {} : { coverUrl: info.thumbnail }),
      ...(published === undefined ? {} : { publishedAt: published * 1000 }),
      ...(info.channel_id === undefined ? {} : { channelId: info.channel_id }),
      ...(info.channel === undefined ? {} : { channelTitle: info.channel }),
      ...(info.language === undefined || info.language === null ? {} : { rawLanguage: languageTag(info.language) }),
      chapters: (info.chapters ?? []).map((chapter) => ({
        startMs: secondsToMs(chapter.start_time),
        ...(chapter.end_time === undefined ? {} : { endMs: secondsToMs(chapter.end_time) }),
        title: chapter.title ?? "",
      })),
      subtitleTracks: captionTracks(info),
    };
  }

  async fetchSubtitle(ref: PlatformContentRef, track: SubtitleTrackRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<CanonicalSubtitle> {
    const locator = JSON.parse(track.locator) as TrackLocator;
    const { value: vtt, acquisition } = await this.guestFirst(auth, async (cookies) => {
      const dir = join(this.options.ytDlp.dataDir, PLATFORM_SCRATCH_DIR, this.newId());
      await mkdir(dir, { recursive: true, mode: 0o700 });
      try {
        await this.options.ytDlp.run({
          args: [
            "--skip-download",
            "--no-playlist",
            locator.automatic ? "--write-auto-subs" : "--write-subs",
            "--sub-langs",
            escapeRegex(locator.key),
            "--sub-format",
            "vtt",
            "--output",
            join(dir, "subtitle"),
            watchUrl(ref.platformContentId),
          ],
          extractors: YOUTUBE_EXTRACTORS,
          ...(cookies === undefined ? {} : { cookies }),
          signal,
          timeoutMs: PLATFORM_METADATA_TIMEOUT_MS,
        });
        const file = (await readdir(dir)).find((name) => name.endsWith(".vtt"));
        if (file === undefined) {
          throw amberError("source_unreachable", "yt-dlp wrote no subtitle file");
        }
        return await readFile(join(dir, file), "utf8");
      } finally {
        await rm(dir, { recursive: true, force: true });
      }
    });
    const parsed = parseTimedSubtitle(locator.automatic ? collapseRollingCaptions(vtt) : vtt);
    return { language: track.language, cues: parsed.cues, acquisition };
  }

  /**
   * Cookies that cannot be a login are `expired` without asking YouTube. Otherwise, with an
   * HTTP client, the home page is read with them and its ytcfg `LOGGED_IN` decides, the
   * field yt-dlp itself reads (`extractor/youtube/_base.py`, `traverse_obj(ytcfg,
   * 'LOGGED_IN')`). A transport error, a non-2xx answer or a page without the field is
   * `unknown`, which leaves the stored status alone. Without a client it stays `unknown`:
   * yt-dlp has no login check and treats rotated cookies as a warning.
   */
  async checkCredential(auth: PlatformCredential, signal: AbortSignal): Promise<"valid" | "expired" | "unknown"> {
    const cookies = parseNetscapeCookies(await auth.cookies());
    const names = new Set(cookies.map((cookie) => cookie.name));
    if (!names.has(LOGIN_COOKIE) || !SAPISID_COOKIES.some((name) => names.has(name))) {
      return "expired";
    }
    const http = this.options.http;
    if (http === undefined) {
      return "unknown";
    }
    try {
      const header = cookieHeaderFor(cookies, HOME_HOST, this.now());
      const response = await platformGet(http, { url: HOME_URL, headers: header === "" ? {} : { Cookie: header }, signal });
      if (response.status < 200 || response.status >= 300) {
        return "unknown";
      }
      const loggedIn = ytcfgLoggedIn(await response.text());
      return loggedIn === undefined ? "unknown" : loggedIn ? "valid" : "expired";
    } catch (error) {
      if (signal.aborted) {
        throw error;
      }
      return "unknown";
    }
  }

  /** Client only: the whole jar of a local browser profile; the caller keeps YouTube's cookies. */
  async importBrowserCookies(browser: CookieBrowser, signal: AbortSignal): Promise<string> {
    return this.options.ytDlp.dumpBrowserCookies({ browser, extractors: YOUTUBE_EXTRACTORS, signal, timeoutMs: PLATFORM_METADATA_TIMEOUT_MS });
  }

  async fetchCollection(platformCollectionId: string, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformCollection> {
    const { value: playlist } = await this.guestFirst(auth, (cookies) =>
      this.options.ytDlp.json<FlatPlaylist>({
        args: ["--dump-single-json", "--flat-playlist", playlistUrl(platformCollectionId)],
        extractors: YOUTUBE_EXTRACTORS,
        ...(cookies === undefined ? {} : { cookies }),
        signal,
        timeoutMs: PLATFORM_METADATA_TIMEOUT_MS,
      }),
    );
    const items = (playlist.entries ?? [])
      .filter((entry): entry is typeof entry & { id: string } => typeof entry.id === "string" && entry.id !== "")
      .map((entry) => ({
        platformContentId: entry.id,
        ...(entry.title === undefined ? {} : { title: entry.title }),
        ...(typeof entry.duration === "number" ? { durationMs: secondsToMs(entry.duration) } : {}),
        canonicalUrl: watchUrl(entry.id),
      }));
    return { title: playlist.title ?? platformCollectionId, items };
  }

  async fetchAudio(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    output: { path: string },
    onProgress: (progress: number) => void,
    signal: AbortSignal,
    options?: { maxBytes?: number },
  ): Promise<{ sizeBytes: number }> {
    const { value } = await this.guestFirst(auth, (cookies) =>
      downloadAudio(this.options.ytDlp, {
        url: watchUrl(ref.platformContentId),
        extractors: YOUTUBE_EXTRACTORS,
        ...(cookies === undefined ? {} : { cookies }),
        output,
        onProgress,
        signal,
        ...(options?.maxBytes === undefined ? {} : { maxBytes: options.maxBytes }),
      }),
    );
    return value;
  }

  /** What an audio cache would download, guest first like every other YouTube call. */
  async inspectAudio(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<{ sizeBytes?: number }> {
    const { value } = await this.guestFirst(auth, (cookies) =>
      inspectAudio(this.options.ytDlp, { url: watchUrl(ref.platformContentId), extractors: YOUTUBE_EXTRACTORS, ...(cookies === undefined ? {} : { cookies }), signal }),
    );
    return value;
  }

  /** What a video cache would download, guest first like every other YouTube call. */
  async inspectVideo(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    options: { maxHeight: number },
    signal: AbortSignal,
  ): Promise<{ hasVideo: false } | { hasVideo: true; mimeType: string; sizeBytes?: number; height?: number; width?: number }> {
    const { value } = await this.guestFirst(auth, (cookies) =>
      inspectVideo(this.options.ytDlp, {
        url: watchUrl(ref.platformContentId),
        extractors: YOUTUBE_EXTRACTORS,
        ...(cookies === undefined ? {} : { cookies }),
        maxHeight: options.maxHeight,
        signal,
      }),
    );
    return value;
  }

  /** The video for `cache_media`, guest first like every other YouTube call. */
  async fetchVideo(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    options: { maxHeight: number; maxBytes: number; output: { path: string; scratchDir: string } },
    onProgress: (progress: number) => void,
    signal: AbortSignal,
  ): Promise<{ sizeBytes: number; mimeType: string; height?: number; acquisition: "guest" | "authenticated" }> {
    const { value, acquisition } = await this.guestFirst(auth, (cookies) =>
      downloadVideo(this.options.ytDlp, {
        url: watchUrl(ref.platformContentId),
        extractors: YOUTUBE_EXTRACTORS,
        ...(cookies === undefined ? {} : { cookies }),
        maxHeight: options.maxHeight,
        maxBytes: options.maxBytes,
        output: options.output,
        onProgress,
        signal,
      }),
    );
    return { ...value, acquisition };
  }

  /** Guest first; one retry with the login when YouTube asks for it and one exists. */
  private async guestFirst<T>(
    auth: PlatformCredential | undefined,
    call: (cookies: string | undefined) => Promise<T>,
  ): Promise<{ value: T; acquisition: "guest" | "authenticated" }> {
    try {
      return { value: await call(undefined), acquisition: "guest" };
    } catch (error) {
      if (auth === undefined || !isAuthProblem(error)) {
        throw error;
      }
    }
    return { value: await call(await auth.cookies()), acquisition: "authenticated" };
  }
}

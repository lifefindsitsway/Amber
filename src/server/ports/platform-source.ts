import type { DanmakuItem } from "../../shared/dto/danmaku.ts";
import type { PlatformDescription } from "../domain/content-description.ts";
import type { CookieBrowser } from "../domain/runtime-support.ts";
import type { Platform } from "../domain/platform.ts";

/**
 * What `parse` recognizes in a URL. A content URL names `platformContentId`
 * (and for bilibili possibly the `p=` part index); a collection or playlist URL names
 * `platformCollectionId` only. `canonicalUrl` is what `Content.source.sourceUrl` stores.
 */
export interface ParsedPlatformUrl {
  canonicalUrl: string;
  platformContentId?: string;
  /** 1-based part number from the URL; the part id itself is only known from metadata. */
  partIndex?: number;
  platformCollectionId?: string;
}

export interface PlatformContentRef {
  platformContentId: string;
  platformPartId?: string;
  platformCollectionId?: string;
  /**
   * The stored canonical source link. Some platforms (Xiaohongshu) need the access parameters
   * it carries to read the page at all. An adapter uses it only when its own `parse` accepts
   * it and names the same `platformContentId`; otherwise it is ignored as if absent.
   */
  sourceUrl?: string;
}

/**
 * Access to the user's platform login, resolved from SecretStore on demand. Adapters do
 * not know how it was obtained (login window, QR code, cookies.txt) and must not keep
 * the decrypted value beyond the request that needs it.
 */
export interface PlatformCredential {
  readonly platform: Platform;
  /** Netscape cookies.txt text, the canonical plaintext of a platform cookie. */
  cookies(): Promise<string>;
}

/**
 * Opaque handle to one subtitle track; `locator` is meaningful only to the adapter that
 * issued it, may embed short-lived signed URLs, and is never persisted or logged.
 */
export interface SubtitleTrackRef {
  locator: string;
  /** BCP-47 tag. */
  language: string;
  label?: string;
  autoGenerated: boolean;
  /** A platform translation of another track; ranked last when a track is chosen. */
  translated: boolean;
}

/** Sentence-level platform subtitles; platforms provide no word timing. */
export interface CanonicalSubtitle {
  language: string;
  cues: Array<{ startMs: number; endMs: number; text: string }>;
  /** Whether the platform login was actually used to obtain it. */
  acquisition: "guest" | "authenticated";
}

/** Creator-provided chapter anchors in platform milliseconds; not tied to any transcript segment. */
export interface PlatformChapter {
  startMs: number;
  endMs?: number;
  title: string;
}

/** One part of a multi-part submission (bilibili 分 P). */
export interface PlatformPart {
  platformPartId: string;
  /** 1-based position as the platform currently orders it. */
  index: number;
  title: string;
  durationMs: number;
  canonicalUrl: string;
}

/**
 * What one read of a platform video's description gave: text, the platform's explicit
 * "none", or nothing readable this time. Defined beside the pure rules that classify it.
 */
export type { PlatformDescription };

export interface PlatformMetadata {
  title: string;
  durationMs: number;
  coverUrl?: string;
  publishedAt?: number;
  channelId?: string;
  channelTitle?: string;
  chapters?: PlatformChapter[];
  subtitleTracks: SubtitleTrackRef[];
  rawLanguage?: string;
  /** Read from the same document as the rest of the metadata; no extra request is made for it. */
  description: PlatformDescription;
}

/**
 * Which video stream a cache takes: exactly the stream of a quality tier (the tier of its
 * picture by the equivalent-height rule of the cache file names), or, for a request that
 * names no tier, the best stream at most `maxHeight` pixels high.
 */
export type VideoTarget = { tier: number } | { maxHeight: number };

/** A tier a video cache can be made in, with the picture size of the stream it downloads. */
export interface VideoQuality {
  tier: number;
  width: number;
  height: number;
}

/**
 * Why a listed entry cannot be imported, as far as the platform's listing tells: `not_video`
 * is an image post in a collection of a platform that mixes both.
 */
export type PlatformEntryUnavailableReason = "private" | "removed" | "unknown" | "not_video";

/** The platform collection a single video belongs to, as the video's own metadata names it. */
export interface PlatformRelatedCollection {
  platformCollectionId: string;
  title: string;
  /** Entries the collection has, when the platform says. */
  itemCount?: number;
  /** 1-based episode number of this video in the collection, when the platform says. */
  index?: number;
  canonicalUrl: string;
}

/**
 * What checking a single link before import found. `video`: a playable video, with the
 * metadata read on the way (kept briefly so the source stage need not ask again). `rejected`:
 * known not to work (`not_video`: an image post; `link_expired`: the access parameter is
 * missing or the platform treats it as expired). `unverified`: the platform did not let us
 * tell (network failure, rate limit, hidden for an unknown reason); the user decides.
 * Refusals that name their own error (a changed signature check, a cooldown) are thrown
 * instead of being reported as `unverified`.
 */
export type PlatformImportCheck =
  | { result: "video"; metadata: PlatformMetadata; relatedCollection?: PlatformRelatedCollection }
  | { result: "rejected"; reason: "not_video" | "link_expired" }
  | { result: "unverified" };

/**
 * One entry of a listed platform collection, before anything per entry is asked of the
 * platform. Whatever the listing itself carries is kept (YouTube lists titles, durations and
 * covers; bilibili lists video ids only).
 */
export interface PlatformCollectionEntry {
  /** 0-based position in the platform's order. */
  index: number;
  platformContentId: string;
  canonicalUrl: string;
  title?: string;
  durationMs?: number;
  /** Only on a trusted platform image host. */
  coverUrl?: string;
  unavailable?: PlatformEntryUnavailableReason;
}

/** A platform collection listed cheaply, in the platform's order, up to the caller's limit. */
export interface PlatformCollectionListing {
  title: string;
  entries: PlatformCollectionEntry[];
  /** Entries the collection has in total; absent when the platform does not say and the listing stopped at the limit. */
  totalCount?: number;
  /** The collection has more entries than the limit, which were not listed. */
  truncated: boolean;
}

/** A listed entry resolved to what importing it creates. */
export interface PlatformCollectionItem {
  platformContentId: string;
  /** Part of the Content identity where the platform has parts (the first part of a multi-part submission). */
  platformPartId?: string;
  canonicalUrl: string;
  /** The title a new Content starts with, until its source stage reads the platform's metadata. */
  title?: string;
  /** What a preview shows; `title` when absent. Never written into a Content. */
  displayTitle?: string;
  /** Of the imported part; a submission's total over several parts is never given here. */
  durationMs?: number;
  /** For the preview only, on a trusted platform image host. */
  coverUrl?: string;
  /** Parts of the submission, where the platform has parts. */
  partCount?: number;
  unavailable?: PlatformEntryUnavailableReason;
}

/**
 * A platform source. Errors are thrown as `AmberError` with the source error classes
 * (`source_unreachable`, `platform_blocked`, `auth_required`,
 * `paid_content`, ...). Every method that goes online takes the Task's or request's
 * `AbortSignal`. Whether and when a given credential is used is the adapter's policy;
 * callers pass the user's credential whenever an account exists.
 */
export interface PlatformSourceAdapter {
  readonly kind: Platform;
  /**
   * Domains whose cookies belong to this platform; pasted or imported cookies are filtered to
   * these. Present exactly when the platform supports a login (with `checkCredential`).
   */
  readonly cookieDomains?: readonly string[];
  /**
   * Pure: accepts only canonical URLs on the platform's supported hosts and returns `null`
   * otherwise. Arbitrary URLs are never handed to yt-dlp.
   */
  parse(url: string): ParsedPlatformUrl | null;
  /**
   * Expands a platform short link hop by hop through the injected `OutboundHttpClient`,
   * checking every hop's host (at most `SHORTLINK_MAX_HOPS`); `null` when the URL is not
   * one of this platform's short links or does not lead to a supported URL.
   */
  resolveUrl?(url: string, signal: AbortSignal): Promise<string | null>;
  /**
   * Present on platforms whose Content identity includes a part id that only metadata
   * reveals (bilibili cid). Import and inspect call it; platforms without
   * parts stay offline for a single video.
   */
  resolveParts?(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformPart[]>;
  fetchMetadata(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformMetadata>;
  /**
   * The video's description alone, in one metadata read. The description belongs to the
   * whole platform video (every bilibili part shares it), so the part id is not needed. The
   * login rule and error classes are those of `fetchMetadata`.
   */
  fetchDescription(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformDescription>;
  fetchSubtitle(ref: PlatformContentRef, track: SubtitleTrackRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<CanonicalSubtitle>;
  /**
   * `expired` when the platform clearly says the login is gone, `valid` when it clearly
   * works, `unknown` for network or transient platform errors (the old credential is kept).
   */
  checkCredential?(auth: PlatformCredential, signal: AbortSignal): Promise<"valid" | "expired" | "unknown">;
  /**
   * Present on platforms whose single links are checked before import. Reads the platform
   * once; `auth` follows the adapter's own login policy (a visitor first where that works).
   */
  precheck?(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformImportCheck>;
  /**
   * Downloads a cover image to `output.path` (a file in the caller's scratch directory) without
   * any login. Only an https URL on this platform's trusted image hosts is fetched; anything
   * else, or more than `options.maxBytes` bytes, fails without writing a usable file. Decoding
   * and re-encoding are the caller's job.
   */
  fetchCover?(coverUrl: string, output: { path: string }, options: { maxBytes: number }, signal: AbortSignal): Promise<{ sizeBytes: number }>;
  /**
   * Lists a collection's entries in the platform's order, at most `limit` of them, in as few
   * requests as the platform allows and without asking anything per entry.
   */
  listCollection(platformCollectionId: string, auth: PlatformCredential | undefined, signal: AbortSignal, limit: number): Promise<PlatformCollectionListing>;
  /**
   * Resolves listed entries of the collection to what importing them creates, one result per
   * entry in the given order. What only decorates a preview (titles, covers) is best effort: a
   * failure to get it leaves the entry as the listing had it. What the Content identity needs
   * fails the whole call when the platform does not answer.
   */
  resolveCollectionEntries(
    platformCollectionId: string,
    entries: readonly PlatformCollectionEntry[],
    auth: PlatformCredential | undefined,
    signal: AbortSignal,
  ): Promise<PlatformCollectionItem[]>;
  /**
   * Downloads the best audio-only stream (yt-dlp `ba/b`) to `output.path`; normalizing it
   * is `LocalMediaIngest.extractAudio`'s job. `maxBytes` is the caller's budget (an audio
   * cache's room on the data volume): a format whose announced size already exceeds it is
   * not downloaded, a download whose bytes pass it is stopped, and a file that turns out
   * larger is refused, all with `media_too_large`.
   */
  fetchAudio(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    output: { path: string },
    onProgress: (progress: number) => void,
    signal: AbortSignal,
    options?: { maxBytes?: number },
  ): Promise<{ sizeBytes: number }>;
  /**
   * Client only (`cache_media`): what an audio cache would download, without
   * downloading it. `sizeBytes` is the selected `ba/b` format's `filesize ?? filesize_approx`
   * when the platform announces one; it feeds the disk budget.
   */
  inspectAudio?(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<{ sizeBytes?: number }>;
  /**
   * Client only (`cache_media`): what `fetchVideo` would download for `target`, without
   * downloading it. `hasVideo = false` when the selected format has no video stream
   * (`vcodec` none or absent): the content is audio only. Otherwise `mimeType` is the
   * container the merge is expected to produce (`video/mp4` or `video/webm`) and `height` /
   * `width` the expected picture size: estimates only, since the cache file is named after
   * the picture size and container ffprobe reads from the finished download. With a `tier`
   * the stream is the one `listVideoQualities` lists for it, and a tier the source no longer
   * offers fails with `invalid_request.cache_quality_unavailable`.
   */
  inspectVideo?(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    target: VideoTarget,
    signal: AbortSignal,
  ): Promise<{ hasVideo: false } | { hasVideo: true; mimeType: string; sizeBytes?: number; height?: number; width?: number }>;
  /**
   * Client only (`cache_media`): the quality tiers a video cache of this source can be made
   * in, with the login this adapter would download with (the same login rule as
   * `inspectVideo`), read from the platform's metadata without downloading. Each entry is the
   * stream `fetchVideo` selects for that tier and its picture size, so a listed tier is one
   * that downloads as itself. Ascending by tier; `undefined` when the metadata holds no
   * format list.
   */
  listVideoQualities?(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<VideoQuality[] | undefined>;
  /**
   * Client only (`cache_media`): downloads the video for `target`, merged into an MP4 or
   * WebM container both WebView2 builds play, to `output.path` inside the caller's scratch
   * directory. With a `tier` the stream is selected again from the current metadata by the
   * same rule as `listVideoQualities` (nothing else is downloaded in its place; a tier the
   * source no longer offers fails with `invalid_request.cache_quality_unavailable`); with a
   * `maxHeight` the best stream at most that high is taken, falling back to any. The
   * intermediate files go below `output.scratchDir`, a directory on the volume of
   * `output.path` that the caller owns and removes, so the finished file is renamed into
   * place without crossing volumes. `maxBytes` is the caller's budget on that volume: when the
   * selected format's `filesize ?? filesize_approx` already exceeds it nothing is downloaded,
   * and a download whose bytes pass it is stopped, both with `media_too_large`.
   */
  fetchVideo?(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    options: VideoTarget & { maxBytes: number; output: { path: string; scratchDir: string } },
    onProgress: (progress: number) => void,
    signal: AbortSignal,
  ): Promise<{ sizeBytes: number; mimeType: string; height?: number; acquisition: "guest" | "authenticated" }>;
  /**
   * Client only: reads this platform's login out of a local browser profile with yt-dlp
   * `--cookies-from-browser`. Returns Netscape cookies.txt text that may
   * hold other sites' cookies; the caller filters it to `cookieDomains` before storing.
   * Every failure is `browser_cookies_unavailable`.
   */
  importBrowserCookies?(browser: CookieBrowser, signal: AbortSignal): Promise<string>;
  /**
   * The danmaku of one video part, fetched anonymously in one request (never with a login),
   * the response read as bytes within `DANMAKU_RESPONSE_MAX_BYTES` and inflated within
   * `DANMAKU_INFLATED_MAX_BYTES`. Only the normal pool; text cleaned and capped; at most
   * `DANMAKU_ITEMS_MAX` items, the lowest weights dropped first (`truncated`). An empty list
   * means the video has none. Only platforms that offer danmaku implement it.
   */
  fetchDanmaku?(ref: PlatformContentRef, signal: AbortSignal): Promise<{ items: DanmakuItem[]; truncated: boolean }>;
}

import type { CookieBrowser } from "../domain/runtime-support.ts";
import type { Platform } from "../domain/platform.ts";

/**
 * What `parse` recognizes in a URL. A content URL names `platformContentId`
 * (and for bilibili possibly the `p=` part index); a collection or playlist URL names
 * `platformCollectionId` only. `canonicalUrl` is what `Content.source.sourceUrl` stores.
 */
export interface ParsedPlatformUrl {
  canonicalUrl: string;
  platformContentId?: string;
  /** 1-based part number from the URL; the part id itself is only known from metadata. */
  partIndex?: number;
  platformCollectionId?: string;
}

export interface PlatformContentRef {
  platformContentId: string;
  platformPartId?: string;
  platformCollectionId?: string;
}

/**
 * Access to the user's platform login, resolved from SecretStore on demand. Adapters do
 * not know how it was obtained (login window, QR code, cookies.txt) and must not keep
 * the decrypted value beyond the request that needs it.
 */
export interface PlatformCredential {
  readonly platform: Platform;
  /** Netscape cookies.txt text, the canonical plaintext of a platform cookie. */
  cookies(): Promise<string>;
}

/**
 * Opaque handle to one subtitle track; `locator` is meaningful only to the adapter that
 * issued it, may embed short-lived signed URLs, and is never persisted or logged.
 */
export interface SubtitleTrackRef {
  locator: string;
  /** BCP-47 tag. */
  language: string;
  label?: string;
  autoGenerated: boolean;
  /** A platform translation of another track; ranked last when a track is chosen. */
  translated: boolean;
}

/** Sentence-level platform subtitles; platforms provide no word timing. */
export interface CanonicalSubtitle {
  language: string;
  cues: Array<{ startMs: number; endMs: number; text: string }>;
  /** Whether the platform login was actually used to obtain it. */
  acquisition: "guest" | "authenticated";
}

/** Creator-provided chapter anchors in platform milliseconds; not tied to any transcript segment. */
export interface PlatformChapter {
  startMs: number;
  endMs?: number;
  title: string;
}

/** One part of a multi-part submission (bilibili 分 P). */
export interface PlatformPart {
  platformPartId: string;
  /** 1-based position as the platform currently orders it. */
  index: number;
  title: string;
  durationMs: number;
  canonicalUrl: string;
}

export interface PlatformMetadata {
  title: string;
  durationMs: number;
  coverUrl?: string;
  publishedAt?: number;
  channelId?: string;
  channelTitle?: string;
  chapters?: PlatformChapter[];
  subtitleTracks: SubtitleTrackRef[];
  rawLanguage?: string;
}

export interface PlatformCollectionItem {
  platformContentId: string;
  platformPartId?: string;
  title?: string;
  durationMs?: number;
  canonicalUrl: string;
}

export interface PlatformCollection {
  title: string;
  items: PlatformCollectionItem[];
}

/**
 * A platform source. Errors are thrown as `AmberError` with the source error classes
 * (`source_unreachable`, `platform_blocked`, `auth_required`,
 * `paid_content`, ...). Every method that goes online takes the Task's or request's
 * `AbortSignal`. Whether and when a given credential is used is the adapter's policy;
 * callers pass the user's credential whenever an account exists.
 */
export interface PlatformSourceAdapter {
  readonly kind: Platform;
  /** Domains whose cookies belong to this platform; pasted or imported cookies are filtered to these. */
  readonly cookieDomains: readonly string[];
  /**
   * Pure: accepts only canonical URLs on the platform's supported hosts and returns `null`
   * otherwise. Arbitrary URLs are never handed to yt-dlp.
   */
  parse(url: string): ParsedPlatformUrl | null;
  /**
   * Expands a platform short link hop by hop through the injected `OutboundHttpClient`,
   * checking every hop's host (at most `SHORTLINK_MAX_HOPS`); `null` when the URL is not
   * one of this platform's short links or does not lead to a supported URL.
   */
  resolveUrl?(url: string, signal: AbortSignal): Promise<string | null>;
  /**
   * Present on platforms whose Content identity includes a part id that only metadata
   * reveals (bilibili cid). Import and inspect call it; platforms without
   * parts stay offline for a single video.
   */
  resolveParts?(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformPart[]>;
  fetchMetadata(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformMetadata>;
  fetchSubtitle(ref: PlatformContentRef, track: SubtitleTrackRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<CanonicalSubtitle>;
  /**
   * `expired` when the platform clearly says the login is gone, `valid` when it clearly
   * works, `unknown` for network or transient platform errors (the old credential is kept).
   */
  checkCredential(auth: PlatformCredential, signal: AbortSignal): Promise<"valid" | "expired" | "unknown">;
  fetchCollection(platformCollectionId: string, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<PlatformCollection>;
  /**
   * Downloads the best audio-only stream (yt-dlp `ba/b`) to `output.path`; normalizing it
   * is `LocalMediaIngest.extractAudio`'s job. `maxBytes` is the caller's budget (an audio
   * cache's room on the data volume): a format whose announced size already exceeds it is
   * not downloaded, a download whose bytes pass it is stopped, and a file that turns out
   * larger is refused, all with `media_too_large`.
   */
  fetchAudio(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    output: { path: string },
    onProgress: (progress: number) => void,
    signal: AbortSignal,
    options?: { maxBytes?: number },
  ): Promise<{ sizeBytes: number }>;
  /**
   * Client only (`cache_media`): what an audio cache would download, without
   * downloading it. `sizeBytes` is the selected `ba/b` format's `filesize ?? filesize_approx`
   * when the platform announces one; it feeds the disk budget.
   */
  inspectAudio?(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<{ sizeBytes?: number }>;
  /**
   * Client only (`cache_media`): what `fetchVideo` would download for
   * `maxHeight`, without downloading it. `hasVideo = false` when the selected format has no
   * video stream (`vcodec` none or absent): the content is audio only. Otherwise
   * `mimeType` is the container the merge is expected to produce (`video/mp4` or
   * `video/webm`) and `height` / `width` the expected picture size: estimates only, since the
   * cache file is named after the picture size and container ffprobe reads from the finished
   * download.
   */
  inspectVideo?(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    options: { maxHeight: number },
    signal: AbortSignal,
  ): Promise<{ hasVideo: false } | { hasVideo: true; mimeType: string; sizeBytes?: number; height?: number; width?: number }>;
  /**
   * Client only (`cache_media`): the video streams the source currently offers with the
   * login this adapter would download with (the same login rule as `inspectVideo`), read
   * from yt-dlp's metadata without downloading. Only streams in an MP4 or WebM container,
   * with a video codec (a string other than `none`) and a positive integer height count;
   * `width` is present when announced. `undefined` when the metadata holds no format list.
   * Candidates only: the format selection of `fetchVideo` may still pick another stream.
   */
  listVideoFormats?(ref: PlatformContentRef, auth: PlatformCredential | undefined, signal: AbortSignal): Promise<Array<{ height: number; width?: number }> | undefined>;
  /**
   * Client only (`cache_media`): downloads the video, at most `maxHeight` pixels
   * high and merged into an MP4 or WebM container both WebView2 builds play, to
   * `output.path` inside the caller's scratch directory. The intermediate files go below
   * `output.scratchDir`, a directory on the volume of `output.path` that the caller owns
   * and removes, so the finished file is renamed into place without crossing volumes.
   * `maxBytes` is the caller's budget on that volume: when the selected format's
   * `filesize ?? filesize_approx` already exceeds it nothing is downloaded, and a download
   * whose bytes pass it is stopped, both with `media_too_large`.
   */
  fetchVideo?(
    ref: PlatformContentRef,
    auth: PlatformCredential | undefined,
    options: { maxHeight: number; maxBytes: number; output: { path: string; scratchDir: string } },
    onProgress: (progress: number) => void,
    signal: AbortSignal,
  ): Promise<{ sizeBytes: number; mimeType: string; height?: number; acquisition: "guest" | "authenticated" }>;
  /**
   * Client only: reads this platform's login out of a local browser profile with yt-dlp
   * `--cookies-from-browser`. Returns Netscape cookies.txt text that may
   * hold other sites' cookies; the caller filters it to `cookieDomains` before storing.
   * Every failure is `browser_cookies_unavailable`.
   */
  importBrowserCookies?(browser: CookieBrowser, signal: AbortSignal): Promise<string>;
}

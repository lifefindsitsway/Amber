/**
 * A document-unique gradient id: inline SVG ids share the page's id space, so two copies of a
 * mark with a fixed id would resolve `url(#…)` to whichever came first (and lose the gradient
 * when that one is hidden). The `useId` value is kept to characters every `url()` parser takes.
 */
function useGradientId(name: string): string {
  return `${name}-${useId().replace(/[^A-Za-z0-9_-]/g, "_")}`;
}


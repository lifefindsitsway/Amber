import { describe, expect, it } from "vitest";
import { PlatformDetailReuse, platformDetailKey } from "../../../src/server/application/platform-detail-reuse.ts";
import type { PlatformMetadata } from "../../../src/server/ports/platform-source.ts";
import { PLATFORM_DETAIL_REUSE_MAX, PLATFORM_DETAIL_REUSE_MS } from "../../../src/shared/defaults.ts";

const NOTE = "64e0a1b2c3d4e5f600112233";
const link = (token: string) => `https://www.xiaohongshu.com/explore/${NOTE}?xsec_token=${token}`;
const VIDEO = "7301234567890123456";

function metadata(title: string): PlatformMetadata {
  return {
    title,
    durationMs: 1000,
    coverUrl: "https://sns-webpic-qc.xhscdn.com/x/xxxxcover",
    subtitleTracks: [{ locator: "https://example.com/signed?sign=xxxx", language: "zh", autoGenerated: false, translated: false }],
    description: { state: "empty" },
  };
}

function clock(start = 1_000_000): { now: () => number; advance: (ms: number) => void } {
  let time = start;
  return { now: () => time, advance: (ms) => void (time += ms) };
}

describe("platformDetailKey", () => {
  it("keys expiring links by the whole link and other platforms by the video id", () => {
    expect(platformDetailKey("xiaohongshu", { platformContentId: NOTE, sourceUrl: link("xxxxa") })).toBe(link("xxxxa"));
    expect(platformDetailKey("xiaohongshu", { platformContentId: NOTE })).toBeUndefined();
    expect(platformDetailKey("douyin", { platformContentId: VIDEO, sourceUrl: `https://www.douyin.com/video/${VIDEO}` })).toBe(VIDEO);
  });
});

describe("PlatformDetailReuse", () => {
  it("answers the same user and link only, until PLATFORM_DETAIL_REUSE_MS has passed", () => {
    const time = clock();
    const reuse = new PlatformDetailReuse({ now: time.now });
    reuse.remember("alice", "xiaohongshu", { platformContentId: NOTE, sourceUrl: link("xxxxa") }, { metadata: metadata("a") });
    expect(reuse.recentMetadata("alice", "xiaohongshu", { platformContentId: NOTE, sourceUrl: link("xxxxa") })?.title).toBe("a");
    expect(reuse.recentMetadata("bob", "xiaohongshu", { platformContentId: NOTE, sourceUrl: link("xxxxa") })).toBeUndefined();
    expect(reuse.recentMetadata("alice", "xiaohongshu", { platformContentId: NOTE, sourceUrl: link("xxxxb") })).toBeUndefined();
    expect(reuse.recentMetadata("alice", "douyin", { platformContentId: NOTE, sourceUrl: link("xxxxa") })).toBeUndefined();
    time.advance(PLATFORM_DETAIL_REUSE_MS - 1);
    expect(reuse.find("alice", "xiaohongshu", { platformContentId: NOTE, sourceUrl: link("xxxxa") })).toBeDefined();
    time.advance(1);
    expect(reuse.find("alice", "xiaohongshu", { platformContentId: NOTE, sourceUrl: link("xxxxa") })).toBeUndefined();
    expect(reuse.size).toBe(0);
  });

  it("keys other platforms by the video id, whatever the link", () => {
    const reuse = new PlatformDetailReuse();
    const related = { platformCollectionId: "douyin:7300000000000000001", title: "mix", itemCount: 3, canonicalUrl: "https://www.douyin.com/collection/7300000000000000001" };
    reuse.remember("alice", "douyin", { platformContentId: VIDEO, sourceUrl: `https://www.douyin.com/video/${VIDEO}` }, { metadata: metadata("d"), relatedCollection: related });
    expect(reuse.find("alice", "douyin", { platformContentId: VIDEO })).toEqual({ metadata: { ...metadata("d"), subtitleTracks: [] }, relatedCollection: related });
  });

  it("drops the earliest stored entry at PLATFORM_DETAIL_REUSE_MAX", () => {
    const reuse = new PlatformDetailReuse();
    const ref = (index: number) => ({ platformContentId: NOTE, sourceUrl: link(`xxxx${index}`) });
    for (let index = 0; index <= PLATFORM_DETAIL_REUSE_MAX; index++) {
      reuse.remember("alice", "xiaohongshu", ref(index), { metadata: metadata(String(index)) });
    }
    expect(reuse.size).toBe(PLATFORM_DETAIL_REUSE_MAX);
    expect(reuse.find("alice", "xiaohongshu", ref(0))).toBeUndefined();
    expect(reuse.find("alice", "xiaohongshu", ref(1))?.metadata.title).toBe("1");
    expect(reuse.find("alice", "xiaohongshu", ref(PLATFORM_DETAIL_REUSE_MAX))?.metadata.title).toBe(String(PLATFORM_DETAIL_REUSE_MAX));
  });

  it("keeps metadata only: no track locators, no login, no copy shared with the caller", () => {
    const reuse = new PlatformDetailReuse();
    const given = metadata("a");
    const ref = { platformContentId: NOTE, sourceUrl: link("xxxxa") };
    reuse.remember("alice", "xiaohongshu", ref, { metadata: given });
    given.title = "changed";
    const kept = reuse.find("alice", "xiaohongshu", ref);
    expect(kept?.metadata.title).toBe("a");
    expect(kept?.metadata.subtitleTracks).toEqual([]);
    expect(JSON.stringify(kept)).not.toMatch(/sign=|cookie|session/i);
    (kept as { metadata: PlatformMetadata }).metadata.title = "mutated";
    expect(reuse.find("alice", "xiaohongshu", ref)?.metadata.title).toBe("a");
  });
});

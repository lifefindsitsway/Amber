const open: Harness[] = [];
afterEach(async () => {
  for (const created of open.splice(0)) await created.close();
});

function harness(): Harness {
  const h = createHarness();
  open.push(h);
  const deps = { repository: h.repository, platforms: h.platformAccess, newId: h.newId };
  h.executors.source = new SourceStageExecutor(deps);
  h.executors.subtitle = new SubtitleStageExecutor(deps);
  return h;
}

function bvid(n: number): string {
  return `BV1sub41c${String(n).padStart(3, "0")}`;
}

const ZH_AUTO: SubtitleTrackRef = { locator: "zh-auto", language: "zh-CN", autoGenerated: true, translated: false };

/** Scripts a bilibili video offering `cues` as its only track, or no track at all. */
function scriptVideo(h: Harness, id: string, durationMs: number, cues: Cue[] | undefined): void {
  h.platforms.bilibili.video(id, {
    metadata: { durationMs, subtitleTracks: cues === undefined ? [] : [ZH_AUTO] },
    ...(cues === undefined ? {} : { subtitles: { [ZH_AUTO.locator]: cues } }),
  });
}

/** Imports the videos and runs their whole process_content with stub downstream stages. */
async function importAndRun(h: Harness, ids: string[]): Promise<Array<{ taskId: string; contentId: string }>> {
  const asrModelRef = configureAsr(h);
  const modelRef = configureLlm(h);
  const { body } = await h.importContent.import(LOCAL, {
    items: ids.map((id) => ({ url: `https://www.bilibili.com/video/${id}` })),
    settings: { autoProofread: false, modelRef, asrModelRef },
  });
  h.scheduler.start();
  await h.scheduler.whenIdle();
  return body.taskIds.map((taskId, index) => ({ taskId, contentId: body.contentIds[index] as string }));
}

function subtitleResult(h: Harness, taskId: string): { verdict: string; reasons: string[]; platformFetch?: string } {
  const run = stageRunsOf(h, taskId).find((candidate) => candidate.stage === "subtitle");
  return JSON.parse(run?.resultJson ?? "{}");
}

/** The `needs_asr` condition as the scheduler evaluates it once the subtitle stage is done. */
function needsAsr(h: Harness, taskId: string, contentId: string): boolean {
  return h.repository.withTransaction((scope) =>
    conditionHolds(
      "needs_asr",
      gatherConditionFacts(scope, {
        mode: "local",
        content: scope.contents.get(LOCAL.userId, contentId),
        request: taskRequestView(taskOf(h, taskId).requestJson),
        stageRuns: scope.stageRuns.listByTask(LOCAL.userId, taskId),
      }),
    ),
  );
}

function contentOf(h: Harness, contentId: string) {
  return h.repository.withTransaction((scope) => scope.contents.get(LOCAL.userId, contentId));
}

function revisionsOf(h: Harness, contentId: string): TranscriptRevision[] {
  return h.repository.withTransaction((scope) => scope.transcripts.listRevisions(LOCAL.userId, contentId));
}

function segmentsOf(h: Harness, revisionId: string): TranscriptSegment[] {
  return h.repository.withTransaction((scope) => scope.transcripts.listSegments(LOCAL.userId, revisionId));
}

/** A platform Content created directly, as if its source stage had already run. */
function platformContent(h: Harness, id: string, durationMs: number, extra: { rawLanguage?: string } = {}): string {
  const contentId = h.newId();
  h.repository.withTransaction((scope) =>
    scope.contents.insert({
      id: contentId,
      userId: LOCAL.userId,
      source: { kind: "bilibili", sourceUrl: `https://www.bilibili.com/video/${id}`, platformContentId: id, platformPartId: `${id}-cid` },
      durationMs,
      ...extra,
      processingStatus: "running",
      createdAt: 1,
      updatedAt: 1,
    }),
  );
  return contentId;
}

/** Runs the subtitle stage once outside the scheduler and publishes its outcome. */
async function runSubtitle(
  h: Harness,
  contentId: string,
  slotted: string[] = [],
): Promise<{ verdict: string; reasons: string[]; platformFetch?: string }> {
  const executor = new SubtitleStageExecutor({ repository: h.repository, platforms: h.platformAccess, newId: h.newId });
  const adapter = h.platforms.bilibili;
  // Records the platform calls made while a heavy slot is held.
  const withHeavySlot = async <T>(work: () => Promise<T>): Promise<T> => {
    const before = adapter.calls.length;
    try {
      return await work();
    } finally {
      slotted.push(...adapter.calls.slice(before).map((call) => call.method));
    }
  };
  const context = { task: { userId: LOCAL.userId, contentId }, signal: new AbortController().signal, withHeavySlot } as unknown as StageExecutionContext;
  const outcome = await executor.run(context);
  h.repository.withTransaction((scope) => outcome.publish?.(scope));
  return outcome.resultJson as { verdict: string; reasons: string[]; platformFetch?: string };
}

/** Stores a revision of `kind` with one sentence and makes it primary. */
function givePrimary(h: Harness, contentId: string, kind: TranscriptKind): string {
  const revisionId = h.newId();
  const generation: TranscriptRevision["generation"] =
    kind === "asr"
      ? { kind: "asr", asrProfileId: "profile", modelId: "scribe_v2" }
      : kind === "imported"
        ? { kind: "imported", format: "srt" }
        : { kind: "manual" };
  const segments: TranscriptSegment[] = [
    { id: h.newId() as SegmentId, revisionId, ordinal: 0, startMs: 0, endMs: 1000, text: `${kind} text`, sourceSegmentIds: [] },
  ];
  h.repository.withTransaction((scope) => {
    scope.transcripts.insertRevision(
      LOCAL.userId,
      { id: revisionId, contentId, kind, language: "zh-CN", timingFidelity: timingFidelityFor(kind), generation, segmentCount: 1, createdAt: 1 },
      segments,
    );
    scope.contents.setPrimaryTranscript(LOCAL.userId, contentId, revisionId, 1);
  });
  return revisionId;
}

describe("subtitle stage verdicts", () => {
  it("judges the four fixtures valid / suspicious / invalid / none, and only a valid one makes ASR unnecessary", async () => {
    const h = harness();
    const names = ["valid", "suspicious", "invalid", "none"] as const;
    names.forEach((name, index) => scriptVideo(h, bvid(index), VERDICT_DURATION_MS, VERDICT_FIXTURES[name].cues));
    const runs = await importAndRun(h, names.map((_, index) => bvid(index)));

    const observed = runs.map(({ taskId, contentId }) => ({
      ...subtitleResult(h, taskId),
      needsAsr: needsAsr(h, taskId, contentId),
      asr: stageStatuses(h, taskId).asr,
    }));
    expect(observed).toEqual(
      names.map((name) => ({
        verdict: VERDICT_FIXTURES[name].verdict,
        reasons: VERDICT_FIXTURES[name].reasons,
        needsAsr: name !== "valid",
        asr: name === "valid" ? "skipped" : "succeeded",
      })),
    );
    // Only the valid working copy became primary; the others are kept but not used.
    const primaries = runs.map(({ contentId }) => contentOf(h, contentId)?.primaryTranscriptRevisionId);
    expect(primaries[0]).toBe(revisionsOf(h, runs[0]?.contentId as string)[0]?.id);
    expect(primaries.slice(1)).toEqual([undefined, undefined, undefined]);
    expect(runs.map(({ contentId }) => revisionsOf(h, contentId).map((revision) => revision.kind))).toEqual([["platform"], ["platform"], ["platform"], []]);
  });

  it("lectures 1 and 2 and the short film of the first course are not valid, lectures 3 to 6 are", async () => {
    const h = harness();
    const lectures = lectureFixtures();
    lectures.forEach((lecture, index) => scriptVideo(h, bvid(index), lecture.durationMs, lecture.cues));
    const runs = await importAndRun(h, lectures.map((_, index) => bvid(index)));

    const verdicts = Object.fromEntries(runs.map(({ taskId }, index) => [lectures[index]?.name, subtitleResult(h, taskId).verdict]));
    expect(verdicts).toEqual({ "01": "invalid", "02": "invalid", "03": "valid", "04": "valid", "05": "valid", "06": "valid", short: "invalid" });
    expect(subtitleResult(h, runs[0]?.taskId as string).reasons).toContain("subtitle_coverage_low");
    // Every line of lecture 2 is "♪ 音乐 ♪": invalid both by its 1 % coverage and as music.
    expect(subtitleResult(h, runs[1]?.taskId as string).reasons).toEqual(["subtitle_incomplete", "subtitle_coverage_low", "subtitle_music_lines"]);
    expect(subtitleResult(h, runs[6]?.taskId as string).reasons).toContain("subtitle_coverage_high");
    expect(runs.map(({ taskId, contentId }) => needsAsr(h, taskId, contentId))).toEqual(lectures.map((lecture) => !lecture.valid));
    // Lecture 3 keeps all 2513 lines.
    const third = contentOf(h, runs[2]?.contentId as string);
    expect(segmentsOf(h, third?.primaryTranscriptRevisionId as string)).toHaveLength(2513);
  });

  it("counts dropped cues with broken timing as a reason", async () => {
    const h = harness();
    const id = bvid(1);
    const cues = [...evenCues(120, VERDICT_DURATION_MS), { startMs: 5000, endMs: 5000, text: "zero length" }, { startMs: -1, endMs: 10, text: "negative" }];
    scriptVideo(h, id, VERDICT_DURATION_MS, cues);
    const contentId = platformContent(h, id, VERDICT_DURATION_MS);
    expect(await runSubtitle(h, contentId)).toEqual({ verdict: "valid", reasons: ["subtitle_cue_dropped"] });
    expect(segmentsOf(h, contentOf(h, contentId)?.primaryTranscriptRevisionId as string)).toHaveLength(120);
  });
});

describe("heavy slots", () => {
  it("fetches the metadata inside a heavy slot and downloads the subtitle outside it, with or without an imported primary", async () => {
    const h = harness();
    scriptVideo(h, bvid(20), VERDICT_DURATION_MS, evenCues(120, VERDICT_DURATION_MS));
    scriptVideo(h, bvid(21), VERDICT_DURATION_MS, evenCues(120, VERDICT_DURATION_MS));
    const workingCopy = platformContent(h, bvid(20), VERDICT_DURATION_MS);
    const alongside = platformContent(h, bvid(21), VERDICT_DURATION_MS);
    givePrimary(h, alongside, "imported");

    for (const contentId of [workingCopy, alongside]) {
      const slotted: string[] = [];
      const before = h.platforms.bilibili.callsOf("fetchSubtitle").length;
      await runSubtitle(h, contentId, slotted);
      expect(slotted).toEqual(["fetchMetadata"]);
      expect(h.platforms.bilibili.callsOf("fetchSubtitle").length).toBe(before + 1);
    }
  });
});

describe("the platform working copy", () => {
  it("stores an identical subtitle once and a changed one as a new revision", async () => {
    const h = harness();
    const id = bvid(2);
    scriptVideo(h, id, VERDICT_DURATION_MS, evenCues(120, VERDICT_DURATION_MS));
    const contentId = platformContent(h, id, VERDICT_DURATION_MS);
    await runSubtitle(h, contentId);
    await runSubtitle(h, contentId);
    expect(revisionsOf(h, contentId)).toHaveLength(1);

    scriptVideo(h, id, VERDICT_DURATION_MS, evenCues(120, VERDICT_DURATION_MS, (index) => `changed ${index}`));
    await runSubtitle(h, contentId);
    const revisions = revisionsOf(h, contentId);
    expect(revisions).toHaveLength(2);
    // A newer valid platform copy replaces the older one as primary.
    expect(contentOf(h, contentId)?.primaryTranscriptRevisionId).toBe(revisions[1]?.id);
  });

  it("becomes primary only over no primary or another root working copy", async () => {
    const h = harness();
    const cues = evenCues(120, VERDICT_DURATION_MS);
    const overAsr = platformContent(h, bvid(3), VERDICT_DURATION_MS);
    const overManual = platformContent(h, bvid(4), VERDICT_DURATION_MS);
    scriptVideo(h, bvid(3), VERDICT_DURATION_MS, cues);
    scriptVideo(h, bvid(4), VERDICT_DURATION_MS, cues);
    givePrimary(h, overAsr, "asr");
    const manual = givePrimary(h, overManual, "manual");

    await runSubtitle(h, overAsr);
    await runSubtitle(h, overManual);
    const platformOf = (contentId: string) => revisionsOf(h, contentId).find((revision) => revision.kind === "platform")?.id;
    expect(contentOf(h, overAsr)?.primaryTranscriptRevisionId).toBe(platformOf(overAsr));
    expect(contentOf(h, overManual)?.primaryTranscriptRevisionId).toBe(manual);
    expect(platformOf(overManual)).toBeDefined();
  });

  it("reuses an identical platform revision the user archived without making it primary", async () => {
    const h = harness();
    const id = bvid(5);
    scriptVideo(h, id, VERDICT_DURATION_MS, evenCues(120, VERDICT_DURATION_MS));
    const contentId = platformContent(h, id, VERDICT_DURATION_MS);
    await runSubtitle(h, contentId);
    const platform = contentOf(h, contentId)?.primaryTranscriptRevisionId as string;
    // The user moved on to an ASR transcript and archived the platform copy.
    const asr = givePrimary(h, contentId, "asr");
    h.repository.withTransaction((scope) => scope.transcripts.setArchived(LOCAL.userId, platform, 5));

    await runSubtitle(h, contentId);
    expect(revisionsOf(h, contentId).filter((revision) => revision.kind === "platform").map((revision) => revision.id)).toEqual([platform]);
    expect(contentOf(h, contentId)?.primaryTranscriptRevisionId).toBe(asr);
    expect(h.repository.withTransaction((scope) => scope.transcripts.listArchived(LOCAL.userId, contentId))).toEqual([{ revisionId: platform, archivedAt: 5 }]);
  });

  it("stores a suspicious subtitle without making it primary", async () => {
    const h = harness();
    scriptVideo(h, bvid(5), VERDICT_DURATION_MS, VERDICT_FIXTURES.suspicious.cues);
    const contentId = platformContent(h, bvid(5), VERDICT_DURATION_MS);
    await runSubtitle(h, contentId);
    expect(revisionsOf(h, contentId)).toHaveLength(1);
    expect(contentOf(h, contentId)?.primaryTranscriptRevisionId).toBeUndefined();
  });

  it("prefers the human track in the original language over automatic, other and translated tracks", async () => {
    const h = harness();
    const id = bvid(6);
    const tracks: SubtitleTrackRef[] = [
      { locator: "en-translated", language: "en", autoGenerated: true, translated: true },
      { locator: "zh-auto", language: "zh-CN", autoGenerated: true, translated: false },
      { locator: "en-human", language: "en", autoGenerated: false, translated: false },
      { locator: "zh-human", language: "zh-CN", autoGenerated: false, translated: false },
    ];
    h.platforms.bilibili.video(id, {
      metadata: { durationMs: VERDICT_DURATION_MS, subtitleTracks: tracks },
      subtitles: Object.fromEntries(tracks.map((track) => [track.locator, evenCues(120, VERDICT_DURATION_MS, () => track.locator)])),
    });
    const contentId = platformContent(h, id, VERDICT_DURATION_MS);
    await runSubtitle(h, contentId);
    expect(h.platforms.bilibili.callsOf("fetchSubtitle").map((call) => call.target)).toEqual([`${id}#zh-human`]);
    const [revision] = revisionsOf(h, contentId);
    expect(revision).toMatchObject({ kind: "platform", language: "zh-CN", timingFidelity: "segment_only", generation: { kind: "platform", acquisition: "guest" } });
    expect(segmentsOf(h, revision?.id as string)[0]?.text).toBe("zh-human");
  });

  it("writes back the original language when it is unknown and keeps a known one", async () => {
    const h = harness();
    const tracks: SubtitleTrackRef[] = [
      { locator: "en-translated", language: "en", autoGenerated: true, translated: true },
      { locator: "ja", language: "ja", autoGenerated: true, translated: false },
    ];
    for (const id of [bvid(7), bvid(8)]) {
      h.platforms.bilibili.video(id, {
        metadata: { durationMs: VERDICT_DURATION_MS, subtitleTracks: tracks },
        subtitles: { ja: evenCues(120, VERDICT_DURATION_MS), "en-translated": evenCues(120, VERDICT_DURATION_MS) },
      });
    }
    const unknown = platformContent(h, bvid(7), VERDICT_DURATION_MS);
    const known = platformContent(h, bvid(8), VERDICT_DURATION_MS, { rawLanguage: "en" });
    await runSubtitle(h, unknown);
    await runSubtitle(h, known);
    expect(contentOf(h, unknown)?.rawLanguage).toBe("ja");
    expect(contentOf(h, known)?.rawLanguage).toBe("en");
  });

  it("writes back the original language even when no track can be used", async () => {
    const h = harness();
    h.platforms.bilibili.video(bvid(9), { metadata: { durationMs: VERDICT_DURATION_MS, subtitleTracks: [], rawLanguage: "zh-CN" } });
    const contentId = platformContent(h, bvid(9), VERDICT_DURATION_MS);
    expect(await runSubtitle(h, contentId)).toEqual({ verdict: "none", reasons: ["subtitle_none"] });
    expect(contentOf(h, contentId)?.rawLanguage).toBe("zh-CN");
  });
});

describe("next to a user-imported subtitle", () => {
  it("stores a fetched platform subtitle but never changes the primary", async () => {
    const h = harness();
    scriptVideo(h, bvid(10), VERDICT_DURATION_MS, evenCues(120, VERDICT_DURATION_MS));
    const contentId = platformContent(h, bvid(10), VERDICT_DURATION_MS);
    const imported = givePrimary(h, contentId, "imported");
    const result = await runSubtitle(h, contentId);
    // The imported sentence covers one second of ten minutes: reported, never acted on.
    expect(result).toEqual({ verdict: "valid", reasons: ["imported_subtitle_invalid", "subtitle_coverage_low"], platformFetch: "stored" });
    expect(contentOf(h, contentId)?.primaryTranscriptRevisionId).toBe(imported);
    expect(revisionsOf(h, contentId).map((revision) => revision.kind).sort()).toEqual(["imported", "platform"]);
  });

  it("reports a missing or failing platform subtitle without failing the stage", async () => {
    const h = harness();
    scriptVideo(h, bvid(11), VERDICT_DURATION_MS, undefined);
    h.platforms.bilibili.video(bvid(12), {
      metadata: { durationMs: VERDICT_DURATION_MS, subtitleTracks: [ZH_AUTO] },
      subtitleError: amberError("platform_blocked", "scripted"),
    });
    const none = platformContent(h, bvid(11), VERDICT_DURATION_MS);
    const failing = platformContent(h, bvid(12), VERDICT_DURATION_MS);
    givePrimary(h, none, "imported");
    const imported = givePrimary(h, failing, "imported");

    expect((await runSubtitle(h, none)).platformFetch).toBe("none");
    const failed = await runSubtitle(h, failing);
    expect(failed.platformFetch).toBe("failed");
    expect(failed.reasons).toContain("platform_subtitle_unavailable");
    expect(contentOf(h, failing)?.primaryTranscriptRevisionId).toBe(imported);
    expect(revisionsOf(h, failing).map((revision) => revision.kind)).toEqual(["imported"]);
  });

  it("never leads to ASR, whatever the platform offers", async () => {
    const h = harness();
    h.platforms.youtube.video("dQw4w9WgXcQ", { metadata: { durationMs: VERDICT_DURATION_MS, subtitleTracks: [] } });
    const asrModelRef = configureAsr(h);
    const modelRef = configureLlm(h);
    const srt = "1\n00:00:00,000 --> 00:09:50,000\nwhole talk\n";
    const { body } = await h.importContent.import(LOCAL, {
      items: [{ url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ", initialSubtitle: { text: srt, language: "en" } }],
      settings: { autoProofread: false, modelRef, asrModelRef },
    });
    h.scheduler.start();
    await h.scheduler.whenIdle();
    const taskId = body.taskIds[0] as string;
    expect(subtitleResult(h, taskId)).toEqual({ verdict: "none", reasons: [], platformFetch: "none" });
    expect(stageStatuses(h, taskId).asr).toBe("skipped");
    expect(taskOf(h, taskId).statusProjection).toBe("succeeded");
  });
});

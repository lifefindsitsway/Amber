function setup(handler?: ProcessHandler) {
  const { ytDlp, runner, dataDir } = scriptedYtDlp(handler);
  return { adapter: new YoutubeAdapter({ ytDlp }), runner, dataDir };
}

/** Answers the first runs from `script` in order, then the last entry forever. */
function sequence(...script: Array<ScriptedProcess | ((spec: ProcessSpec) => ScriptedProcess)>): ProcessHandler {
  let index = 0;
  return (spec) => {
    const next = script[Math.min(index++, script.length - 1)] as ScriptedProcess | ((spec: ProcessSpec) => ScriptedProcess);
    return typeof next === "function" ? next(spec) : next;
  };
}

async function errorOf(promise: Promise<unknown>): Promise<AppError> {
  try {
    await promise;
  } catch (error) {
    if (isAmberError(error)) {
      return error.appError;
    }
    throw error;
  }
  throw new Error("expected a rejection");
}


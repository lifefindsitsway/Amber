  const page = (loggedIn: boolean) =>
    `<html><script>ytcfg.set("EXPERIMENT_FLAGS", {});ytcfg.set({"INNERTUBE_API_KEY":"<placeholder>","LOGGED_IN":${loggedIn},"VISITOR_DATA":"x"});</script></html>`;


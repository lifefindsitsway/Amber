describe("YoutubeAdapter.importBrowserCookies", () => {
  const JAR = `# Netscape HTTP Cookie File\n${cookieLine(".youtube.com", "LOGIN_INFO")}\n${cookieLine(".example.org", "other")}\n`;

  /** Plays yt-dlp without a URL: dumps `jar` into the `--cookies` file and exits with `exitCode`. */
  function browserRun(exitCode: number, jar: string | undefined): ProcessHandler {
    return (spec) => {
      const file = argAfter(spec.args, "--cookies") as string;
      expect(readFileSync(file, "utf8")).toBe("# Netscape HTTP Cookie File\n");
      if (process.platform !== "win32") {
        expect(statSync(file).mode & 0o777).toBe(0o600);
      }
      if (jar !== undefined) {
        writeFileSync(file, jar);
      }
      return { exitCode, stderr: exitCode === 2 ? "Usage: yt-dlp [OPTIONS] URL [URL...]\n\nyt-dlp: error: You must provide at least one URL." : "ERROR: could not find firefox cookies database" };
    };
  }

  it("returns the jar yt-dlp dumped without a URL and removes the file", async () => {
    const { adapter, runner, dataDir } = setup(browserRun(2, JAR));
    expect(await adapter.importBrowserCookies("chrome", signal())).toBe(JAR);
    const args = runner.specs[0]?.args ?? [];
    expect(argAfter(args, "--cookies-from-browser")).toBe("chrome");
    const file = argAfter(args, "--cookies") as string;
    expect(dirname(file)).toBe(join(dataDir, COOKIES_DIR));
    expect(file).toMatch(/[0-9A-HJKMNP-TV-Z]{26}\.txt$/);
    expect(args.some((arg) => /^https?:/.test(arg))).toBe(false);
    expect(existsSync(file)).toBe(false);
  });

  it("is browser_cookies_unavailable when yt-dlp cannot read the profile, writes nothing, times out or fails to start", async () => {
    const cases: ProcessHandler[] = [
      browserRun(1, undefined),
      browserRun(0, JAR),
      (spec) => {
        rmSync(argAfter(spec.args, "--cookies") as string);
        return { exitCode: 2 };
      },
      () => {
        throw Object.assign(new Error("timed out"), { reason: "timeout" });
      },
      () => {
        throw new Error("spawn ENOENT");
      },
    ];
    for (const handler of cases) {
      const { adapter, runner } = setup(handler);
      expect((await errorOf(adapter.importBrowserCookies("firefox", signal()))).class).toBe("browser_cookies_unavailable");
      expect(existsSync(argAfter(runner.specs[0]?.args ?? [], "--cookies") as string)).toBe(false);
    }
  });

  it("passes a cancellation through as is", async () => {
    const controller = new AbortController();
    const aborted = new Error("aborted");
    const { adapter } = setup(() => {
      controller.abort();
      throw aborted;
    });
    await expect(adapter.importBrowserCookies("edge", controller.signal)).rejects.toBe(aborted);
  });
});


const LOGIN = credential("youtube", [cookieLine(".youtube.com", "LOGIN_INFO"), cookieLine(".youtube.com", "__Secure-3PAPISID")]);
const BOT_CHECK: ScriptedProcess = { exitCode: 1, stderr: "ERROR: [youtube] dQw4w9WgXcQ: Sign in to confirm you’re not a bot. Use --cookies-from-browser or --cookies" };

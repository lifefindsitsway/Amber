import { afterEach, describe, expect, it } from "vitest";
import { LOCAL_TOKEN } from "../fixtures/pipeline/harness.ts";
import { CurlClient } from "../fixtures/pipeline/curl.ts";
import { createDemoStack, type DemoStack } from "../fixtures/pipeline/demo-stack.ts";
import { evenCues } from "../fixtures/platform/subtitles.ts";

/**
 * API pipeline demo: the API-level pipeline closed loop, driven by `curl` against a real socket with
 * replayed platform, ASR and LLM edges (zero outbound calls). Two lectures enter one
 * collection: one with a valid platform subtitle (ASR skipped), one without (ASR replay).
 */

const WITH_SUBTITLE = "dmo1subtitl";
const WITHOUT_SUBTITLE = "dmo1asronly";
const TERMINAL = new Set(["succeeded", "failed", "cancelled"]);
const POLL_TIMEOUT_MS = 30_000;

interface TaskDetail {
  statusProjection: string;
  stageRuns: Array<{ stage: string; status: string; attempt: number }>;
}

interface Citation {
  transcriptRevisionId: string;
  segmentId: string;
}

const open: DemoStack[] = [];
afterEach(async () => {
  for (const stack of open.splice(0)) await stack.close();
});

function scriptVideos(stack: DemoStack): void {
  const lines = ["今天讲检索增强生成。", "先看向量数据库。", "再看重排序。", "然后是评估方法。", "最后讲上线监控。", "下节课再见。"];
  stack.h.platforms.youtube
    .video(WITH_SUBTITLE, {
      metadata: {
        title: "第一讲",
        durationMs: 60_000,
        rawLanguage: "zh-CN",
        subtitleTracks: [{ locator: "zh", language: "zh-CN", autoGenerated: false, translated: false }],
      },
      subtitles: { zh: evenCues(lines.length, 60_000, (index) => lines[index] as string) },
    })
    .video(WITHOUT_SUBTITLE, { metadata: { title: "第二讲", durationMs: 3000, rawLanguage: "zh-CN", subtitleTracks: [] } });
}

/** Polls the task snapshot without recording each poll; the first poll is recorded once. */
async function untilTerminal(curl: CurlClient, taskId: string): Promise<TaskDetail> {
  const deadline = Date.now() + POLL_TIMEOUT_MS;
  let first = true;
  for (;;) {
    const response = await curl.request("GET", `/api/tasks/${taskId}`, undefined, { record: first });
    first = false;
    expect(response.status).toBe(200);
    const task = response.json as TaskDetail;
    if (TERMINAL.has(task.statusProjection)) {
      return task;
    }
    if (Date.now() > deadline) {
      throw new Error(`task ${taskId} still ${task.statusProjection}`);
    }
    await new Promise((resolve) => setTimeout(resolve, 50));
  }
}

const statusesOf = (task: TaskDetail): Record<string, string> => Object.fromEntries(task.stageRuns.map((run) => [run.stage, run.status]));

/** End to end: every citation names a sentence that the segments endpoint returns. */
async function expectCitationsResolve(curl: CurlClient, citations: readonly Citation[]): Promise<void> {
  expect(citations.length).toBeGreaterThan(0);
  const byRevision = new Map<string, Set<string>>();
  for (const { transcriptRevisionId } of citations) {
    if (!byRevision.has(transcriptRevisionId)) {
      const segments = await curl.request("GET", `/api/transcript/revisions/${transcriptRevisionId}/segments?limit=100`);
      expect(segments.status).toBe(200);
      byRevision.set(transcriptRevisionId, new Set((segments.json as { items: Array<{ id: string }> }).items.map((item) => item.id)));
    }
  }
  for (const citation of citations) {
    expect(byRevision.get(citation.transcriptRevisionId)?.has(citation.segmentId)).toBe(true);
  }
}

describe("API pipeline demo: curl drives import → stages → summary → collection summary", () => {
  it("every step answers 2xx and the collection summary resolves to real sentences", { timeout: 60_000 }, async () => {
    const stack = await createDemoStack();
    open.push(stack);
    scriptVideos(stack);
    const curl = new CurlClient(stack.baseUrl, LOCAL_TOKEN);

    const provider = await curl.request("POST", "/api/providers", {
      name: "replay",
      protocol: "openai_compatible",
      baseURL: "https://llm.example.com/v1",
      models: [{ modelId: "model-a", contextWindowTokens: 128_000 }],
    });
    expect(provider.status).toBe(201);
    const providerProfileId = (provider.json as { id: string }).id;
    expect((await curl.request("PUT", `/api/providers/${providerProfileId}/credential`, { value: "<placeholder-llm-key>" })).status).toBe(200);
    const asrProfile = await curl.request("POST", "/api/asr-profiles", { name: "ElevenLabs", provider: "elevenlabs" });
    expect(asrProfile.status).toBe(201);
    const asrProfileId = (asrProfile.json as { id: string }).id;
    // A new profile starts with the provider's recommended models; the first one is chosen.
    const asrModelRef = { asrProfileId, modelId: (asrProfile.json as { models: Array<{ modelId: string }> }).models[0]?.modelId as string };
    expect((await curl.request("PUT", `/api/asr-profiles/${asrProfileId}/credential`, { value: "<placeholder-asr-key>" })).status).toBe(200);
    const modelRef = { providerProfileId, modelId: "model-a" };

    const collection = await curl.request("POST", "/api/collections", { name: "Demo 课程" });
    expect(collection.status).toBe(201);
    const collectionId = (collection.json as { id: string }).id;

    const imported = await curl.request("POST", "/api/contents/import", {
      items: [{ url: `https://www.youtube.com/watch?v=${WITH_SUBTITLE}` }, { url: `https://www.youtube.com/watch?v=${WITHOUT_SUBTITLE}` }],
      settings: { modelRef, asrModelRef, autoProofread: true },
      collection: { id: collectionId },
    });
    expect(imported.status).toBe(202);
    const { taskIds, contentIds } = imported.json as { taskIds: string[]; contentIds: string[] };
    expect(taskIds).toHaveLength(2);

    const tasks = [];
    for (const taskId of taskIds) {
      tasks.push(await untilTerminal(curl, taskId));
    }
    for (const task of tasks) {
      expect(task.statusProjection).toBe("succeeded");
      expect(Object.values(statusesOf(task))).not.toContain("failed");
    }
    expect(statusesOf(tasks[0] as TaskDetail)).toEqual({
      source: "succeeded",
      subtitle: "succeeded",
      asr: "skipped",
      proofread: "succeeded",
      chapter: "succeeded",
      summary: "succeeded",
    });
    expect(statusesOf(tasks[1] as TaskDetail)).toEqual({
      source: "succeeded",
      subtitle: "succeeded",
      asr: "succeeded",
      proofread: "succeeded",
      chapter: "succeeded",
      summary: "succeeded",
    });
    expect(stack.asr.calls).toHaveLength(1);

    for (const contentId of contentIds) {
      const chapters = await curl.request("GET", `/api/contents/${contentId}/chapters`);
      expect(chapters.status).toBe(200);
      expect((chapters.json as { current?: { origin: { kind: string } } }).current?.origin.kind).toBe("ai");
      const summaries = await curl.request("GET", `/api/contents/${contentId}/summaries`);
      expect(summaries.status).toBe(200);
      const core = (summaries.json as { templates: Array<{ template: { id: string }; current?: { citations: Citation[] }; stale: boolean }> }).templates.find(
        (entry) => entry.template.id === "summary.core",
      );
      expect(core?.stale).toBe(false);
      await expectCitationsResolve(curl, core?.current?.citations ?? []);
    }

    const accepted = await curl.request("POST", `/api/collections/${collectionId}/summary`, { modelRef });
    expect(accepted.status).toBe(202);
    const summaryTask = await untilTerminal(curl, (accepted.json as { taskId: string }).taskId);
    expect(summaryTask.statusProjection).toBe("succeeded");
    expect(statusesOf(summaryTask)).toEqual({ collection_summary: "succeeded" });

    const summary = await curl.request("GET", `/api/collections/${collectionId}/summary`);
    expect(summary.status).toBe(200);
    const current = (summary.json as { current?: { body: string; citations: Citation[]; partials: unknown[]; inputItems: unknown[] }; stale: boolean }).current;
    // A collection summary carries no citations.
    expect(current?.body).not.toContain("[[");
    expect(current?.citations).toEqual([]);
    expect(current?.inputItems).toHaveLength(2);
    expect(current?.partials).toHaveLength(1);
    expect((summary.json as { stale: boolean }).stale).toBe(false);

    expect(stack.llm.kinds()).toEqual(
      expect.arrayContaining(["proofread", "chapter", "envelope", "partial", "carry", "final_collection"]),
    );
    console.info(`API pipeline demo curl sequence:\n${curl.transcript.join("\n")}`);
  });
});
